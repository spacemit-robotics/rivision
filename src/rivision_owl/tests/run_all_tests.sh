#!/bin/bash
# 运行所有测试

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

echo "╔══════════════════════════════════════════════════════════════════╗"
echo "║              RiVision-OWL 完整测试套件                            ║"
echo "╚══════════════════════════════════════════════════════════════════╝"
echo ""

# 1. 单元测试
echo "═══════════════════════════════════════════════════════════════════"
echo "  [1/3] 单元测试"
echo "═══════════════════════════════════════════════════════════════════"
cd "$SCRIPT_DIR/../gb28181-sim"
go test ./... -v -cover
UNIT_RESULT=$?

echo ""
echo "═══════════════════════════════════════════════════════════════════"
echo "  [2/3] 集成测试"
echo "═══════════════════════════════════════════════════════════════════"
"$SCRIPT_DIR/integration_test.sh"
INT_RESULT=$?

echo ""
echo "═══════════════════════════════════════════════════════════════════"
echo "  [3/3] 端到端测试"
echo "═══════════════════════════════════════════════════════════════════"
"$SCRIPT_DIR/e2e_test.sh"
E2E_RESULT=$?

echo ""
echo "╔══════════════════════════════════════════════════════════════════╗"
echo "║                       测试汇总                                    ║"
echo "╠══════════════════════════════════════════════════════════════════╣"
[ $UNIT_RESULT -eq 0 ] && echo "║  ✓ 单元测试: 通过                                               ║" || echo "║  ✗ 单元测试: 失败                                               ║"
[ $INT_RESULT -eq 0 ] && echo "║  ✓ 集成测试: 通过                                               ║" || echo "║  ✗ 集成测试: 失败                                               ║"
[ $E2E_RESULT -eq 0 ] && echo "║  ✓ 端到端测试: 通过                                             ║" || echo "║  ✗ 端到端测试: 失败                                             ║"
echo "╚══════════════════════════════════════════════════════════════════╝"

# 返回总体结果
[ $UNIT_RESULT -eq 0 ] && [ $INT_RESULT -eq 0 ] && [ $E2E_RESULT -eq 0 ]
