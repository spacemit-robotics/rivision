// ─── Response parsers ───────────────────────────────────────────────────────

// parseResponse auto-detects wrapped {code,data} vs direct response.
// Returns the "payload" (either .data or the raw body).
func (c *Client) parseResponse(body []byte) (json.RawMessage, error) {
	var wrapped struct {
		Code int             `json:"code"`
		Msg  string          `json:"msg"`
		Data json.RawMessage `json:"data"`
	}
	if err := json.Unmarshal(body, &wrapped); err == nil {
		hasWrapped := len(wrapped.Data) > 0 || wrapped.Msg != "" || strings.Contains(string(body), `"code"`)
		if hasWrapped {
			if wrapped.Code != 0 && wrapped.Code != 200 {
				return nil, fmt.Errorf("OWL error %d: %s", wrapped.Code, wrapped.Msg)
			}
			if len(wrapped.Data) > 0 {
				return wrapped.Data, nil
			}
		}
	}
	// Direct format
	return json.RawMessage(body), nil
}

func (c *Client) parseDeviceList(body []byte) ([]Device, error) {
	parsed, err := c.parseResponse(body)
	if err != nil {
		return nil, err
	}

	// Try direct array
	var devices []Device
	if json.Unmarshal(parsed, &devices) == nil && len(devices) > 0 {
		return devices, nil
	}

	// Try {items: [...]} wrapper
	var wrapper struct {
		Items   []Device `json:"items"`
		Devices []Device `json:"devices"`
		Total   int      `json:"total"`
	}
	if json.Unmarshal(parsed, &wrapper) == nil {
		if len(wrapper.Items) > 0 {
			return wrapper.Items, nil
		}
		if len(wrapper.Devices) > 0 {
			return wrapper.Devices, nil
		}
	}

	// Try top-level items (non-wrapped response)
	var topLevel struct {
		Items []Device `json:"items"`
		Total int      `json:"total"`
	}
	if json.Unmarshal(body, &topLevel) == nil && len(topLevel.Items) > 0 {
		return topLevel.Items, nil
	}

	return nil, fmt.Errorf("cannot parse device list")
}

func (c *Client) parseChannelList(body []byte) ([]Channel, error) {
	parsed, err := c.parseResponse(body)
	if err != nil {
		return nil, err
	}

	var channels []Channel
	if json.Unmarshal(parsed, &channels) == nil && len(channels) > 0 {
		return channels, nil
	}

	var wrapper struct {
		Items    []Channel `json:"items"`
		Channels []Channel `json:"channels"`
		Total    int       `json:"total"`
	}
	if json.Unmarshal(parsed, &wrapper) == nil {
		if len(wrapper.Items) > 0 {
			return wrapper.Items, nil
		}
		if len(wrapper.Channels) > 0 {
			return wrapper.Channels, nil
		}
	}

	var topLevel struct {
		Items []Channel `json:"items"`
		Total int       `json:"total"`
	}
	if json.Unmarshal(body, &topLevel) == nil && len(topLevel.Items) > 0 {
		return topLevel.Items, nil
	}

	return nil, fmt.Errorf("cannot parse channel list")
}

func (c *Client) parsePlayResult(body []byte) (*PlayResult, error) {
	parsed, err := c.parseResponse(body)
	if err != nil {
		return nil, err
	}

	// Standard format: {app, stream, items: [{rtsp, ...}]}
	var result PlayResult
	if json.Unmarshal(parsed, &result) == nil {
		if len(result.Items) > 0 || len(result.URLs) > 0 {
			return &result, nil
		}
	}

	// GoWVP compat: {app, stream, urls: {rtsp: "...", ...}}
	var goWVP struct {
		App    string            `json:"app"`
		Stream string            `json:"stream"`
		URLs   map[string]string `json:"urls"`
	}
	if json.Unmarshal(parsed, &goWVP) == nil && len(goWVP.URLs) > 0 {
		return &PlayResult{App: goWVP.App, Stream: goWVP.Stream, URLs: goWVP.URLs}, nil
	}

	return nil, fmt.Errorf("cannot parse play result")
}

// ─── HTTP helpers with auth ─────────────────────────────────────────────────

func (c *Client) setAuthHeaders(req *http.Request) {
	c.mu.RLock()
	token := c.token
	c.mu.RUnlock()
	if token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}
	req.Header.Set("User-Agent", "rivision-hub/owl-client")
}

func (c *Client) doGet(ctx context.Context, rawURL string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, rawURL, nil)
	if err != nil {
		return nil, err
	}
	return c.doRequest(req)
}

func (c *Client) doGetAuth(ctx context.Context, rawURL string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, rawURL, nil)
	if err != nil {
		return nil, err
	}
	c.setAuthHeaders(req)
	return c.doRequest(req)
}

// doGetAuthRetry does GET with auth, and retries once after re-login on 401.
func (c *Client) doGetAuthRetry(ctx context.Context, rawURL string) ([]byte, error) {
	body, err := c.doGetAuth(ctx, rawURL)
	if err != nil && c.isAuthError(err) {
		c.clearToken()
		if loginErr := c.Login(ctx); loginErr == nil {
			return c.doGetAuth(ctx, rawURL)
		}
	}
	return body, err
}

func (c *Client) doPostAuth(ctx context.Context, rawURL string, body []byte) ([]byte, error) {
	var bodyReader io.Reader
	if body != nil {
		bodyReader = bytes.NewReader(body)
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, rawURL, bodyReader)
	if err != nil {
		return nil, err
	}
	c.setAuthHeaders(req)
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	return c.doRequest(req)
}

// doPostAuthRetry does POST with auth, retries once after re-login on 401.
func (c *Client) doPostAuthRetry(ctx context.Context, rawURL string, body []byte) ([]byte, error) {
	respBody, err := c.doPostAuth(ctx, rawURL, body)
	if err != nil && c.isAuthError(err) {
		c.clearToken()
		if loginErr := c.Login(ctx); loginErr == nil {
			return c.doPostAuth(ctx, rawURL, body)
		}
	}
	return respBody, err
}

func (c *Client) doDeleteAuth(ctx context.Context, rawURL string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodDelete, rawURL, nil)
	if err != nil {
		return nil, err
	}
	c.setAuthHeaders(req)
	respBody, err := c.doRequest(req)
	if err != nil && c.isAuthError(err) {
		c.clearToken()
		if loginErr := c.Login(ctx); loginErr == nil {
			req2, _ := http.NewRequestWithContext(ctx, http.MethodDelete, rawURL, nil)
			c.setAuthHeaders(req2)
			return c.doRequest(req2)
		}
	}
	return respBody, err
}

// doPostRaw does POST without auth headers (used for login).
func (c *Client) doPostRaw(ctx context.Context, rawURL string, data interface{}) ([]byte, error) {
	jsonData, err := json.Marshal(data)
	if err != nil {
		return nil, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, rawURL, bytes.NewReader(jsonData))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("User-Agent", "rivision-hub/owl-client")
	return c.doRequest(req)
}

func (c *Client) doRequest(req *http.Request) ([]byte, error) {
	resp, err := c.client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	body, err := io.ReadAll(io.LimitReader(resp.Body, 2<<20))
	if err != nil {
		return nil, err
	}

	if resp.StatusCode >= 400 {
		return body, fmt.Errorf("OWL API %s %s: HTTP %d: %s",
			req.Method, req.URL.Path, resp.StatusCode, strings.TrimSpace(string(body)))
	}
	return body, nil
}

func (c *Client) isAuthError(err error) bool {
	if err == nil {
		return false
	}
	msg := err.Error()
	return strings.Contains(msg, "HTTP 401") || strings.Contains(msg, "HTTP 403")
}
