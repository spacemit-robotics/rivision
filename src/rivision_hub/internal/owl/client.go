// PlayRemoteRequest directs Hub OWL to send SIP INVITE with a remote ZLM as media target.
// Camera sends RTP directly to the specified ZLM (on Worker machine), not to Hub's local ZLM.
type PlayRemoteRequest struct {
	ZLMHost     string `json:"zlm_host"`                // Worker ZLM IP
	ZLMHTTPPort int    `json:"zlm_http_port,omitempty"` // Worker ZLM HTTP API port (default 80)
	ZLMRTPPort  int    `json:"zlm_rtp_port,omitempty"`  // 0 = auto-allocate
}

// PlayRemote tells Hub OWL to set up a stream with media going to a remote Worker ZLM.
// Hub OWL handles SIP signaling (INVITE/BYE), but video flows Camera→Worker ZLM directly.
// Returns streaming URLs on the remote ZLM.
func (c *Client) PlayRemote(ctx context.Context, channelID string, req PlayRemoteRequest) (*PlayResult, error) {
	if err := c.EnsureLogin(ctx); err != nil {
		return nil, err
	}

	escaped := url.PathEscape(channelID)
	payload, _ := json.Marshal(req)

	// Try play-remote endpoint first, fallback to standard play with query params
	for _, path := range []string{
		"/api/channels/%s/play-remote",
		"/channels/%s/play-remote",
	} {
		body, err := c.doPostAuthRetry(ctx, c.baseURL+fmt.Sprintf(path, escaped), payload)
		if err != nil {
			continue
		}
		result, err := c.parsePlayResult(body)
		if err == nil {
			return result, nil
		}
	}

	// Do NOT fall back to standard PlayChannel — that would route media to Hub's local ZLM,
	// violating the "Hub zero video" architecture. Instead, return an error so the caller
	// can handle it explicitly (e.g., switch to worker_owl mode or alert the operator).
	return nil, fmt.Errorf("PlayRemote not supported by OWL at %s for channel %s: cannot route media to Worker %s (play-remote endpoint unavailable)", c.baseURL, channelID, req.ZLMHost)
}

// StopChannel stops playback of a channel.
