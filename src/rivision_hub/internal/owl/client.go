// Package owl provides a production-grade HTTP client for rivision_owl's REST API.
//
// Architecture:
//
//	rivision_owl (Host-side) handles all protocol-level complexity:
//	  - GB28181: SIP REGISTER/INVITE → RTP → ZLMediaKit → RTSP
//	  - ONVIF:  WS-Discovery → GetStreamUri → RTSP
//	  - RTMP/RTSP: stream proxy via ZLMediaKit
//
//	Hub calls OWL HTTP API to:
//	  1. Add/manage devices (GB28181 / ONVIF)
//	  2. Trigger playback → get RTSP URLs
//	  3. Discover ONVIF cameras on the network
//	  4. Retrieve snapshots, control PTZ
//
//	Hub then assigns the resolved RTSP URLs to Workers via scheduler.
//	Workers never handle GB28181/ONVIF directly — only plain RTSP.
//
// Production features (ported from rivision_cli):
//   - Authentication: Plain + RSA OAEP/SHA256 dual-mode with auto-fallback
//   - API path fallbacks: /api/xxx → /xxx for GoWVP vs rivision_owl compat
//   - Response parsing: auto-detect {code,msg,data} wrapped vs direct JSON
//   - Pagination: full traversal with dedup and loop protection
//   - RTSP URL caching: 5min TTL to avoid repeated SIP INVITE
//   - Token refresh: auto re-login on 401 and retry
package owl

