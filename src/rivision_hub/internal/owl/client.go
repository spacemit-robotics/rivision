// GetSnapshotURL returns the snapshot URL for a channel.
func (c *Client) GetSnapshotURL(channelID string) string {
	return c.baseURL + "/channels/" + url.PathEscape(channelID) + "/snapshot"
}

// Snapshot captures a JPEG snapshot with auth headers.
func (c *Client) Snapshot(ctx context.Context, channelID string) ([]byte, error) {
	if err := c.EnsureLogin(ctx); err != nil {
		return nil, err
	}

	escaped := url.PathEscape(channelID)
	for _, path := range []string{"/api/channels/%s/snapshot", "/channels/%s/snapshot"} {
		u := c.baseURL + fmt.Sprintf(path, escaped)
		req, err := http.NewRequestWithContext(ctx, http.MethodPost, u, nil)
		if err != nil {
			continue
		}
		c.setAuthHeaders(req)
		resp, err := c.client.Do(req)
		if err != nil {
			continue
		}
		defer resp.Body.Close()
		if resp.StatusCode < 400 {
			return io.ReadAll(io.LimitReader(resp.Body, 10<<20))
		}
	}
	return nil, fmt.Errorf("Snapshot %s: all endpoints failed", channelID)
}

