// ListDevicesWithChannels returns all devices and their child channels.
func (c *Client) ListDevicesWithChannels(ctx context.Context) ([]Device, error) {
	if err := c.EnsureLogin(ctx); err != nil {
		return nil, err
	}

	params := "page=1&size=200"

	// Try multiple paths for GoWVP vs rivision_owl compatibility
	for _, path := range []string{"/api/devices/channels", "/devices/channels"} {
		body, err := c.doGetAuthRetry(ctx, c.baseURL+path+"?"+params)
		if err != nil {
			continue
		}
		devices, err := c.parseDeviceList(body)
		if err == nil {
			return devices, nil
		}
	}
	return nil, fmt.Errorf("devices/channels endpoint unavailable")
}

