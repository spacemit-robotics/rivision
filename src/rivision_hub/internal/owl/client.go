func (c *Client) ListChannelsByDevice(ctx context.Context, deviceID string) ([]Channel, error) {
	return c.listChannelsPage(ctx, 1, 200, deviceID)
}

// GetAllChannels returns ALL channels across all pages with dedup.
func (c *Client) GetAllChannels(ctx context.Context) ([]Channel, error) {
	if err := c.EnsureLogin(ctx); err != nil {
		return nil, err
	}

	var all []Channel
	seen := make(map[string]struct{})
	pageSize := 100
	maxPages := 20

	for page := 1; page <= maxPages; page++ {
		items, err := c.listChannelsPage(ctx, page, pageSize, "")
		if err != nil {
			if page == 1 {
				return nil, err
			}
			break
		}

		added := 0
		for _, ch := range items {
			id := ch.ID
			if id == "" {
				id = ch.ChannelID
			}
			if id == "" {
				continue
			}
			if _, ok := seen[id]; ok {
				continue
			}
			seen[id] = struct{}{}
			all = append(all, ch)
			added++
		}

		// Loop protection: no new items or empty page
		if len(items) == 0 || added == 0 {
			break
		}
		if len(all) >= len(items)*maxPages {
			break
		}
	}
	return all, nil
}

// GetChannel returns a single channel by ID.
func (c *Client) GetChannel(ctx context.Context, channelID string) (*Channel, error) {
	if err := c.EnsureLogin(ctx); err != nil {
		return nil, err
	}

	escaped := url.PathEscape(channelID)
	for _, path := range []string{"/api/channels/", "/channels/"} {
		body, err := c.doGetAuthRetry(ctx, c.baseURL+path+escaped)
		if err != nil {
			continue
		}
		parsed, err := c.parseResponse(body)
		if err != nil {
			continue
		}
		var ch Channel
		if json.Unmarshal(parsed, &ch) == nil && (ch.ID != "" || ch.ChannelID != "") {
			return &ch, nil
		}
	}
	return nil, fmt.Errorf("GetChannel %s: not found", channelID)
}

func (c *Client) listChannelsPage(ctx context.Context, page, pageSize int, deviceID string) ([]Channel, error) {
	if err := c.EnsureLogin(ctx); err != nil {
		return nil, err
	}

	params := url.Values{}
	params.Set("page", fmt.Sprintf("%d", page))
	params.Set("size", fmt.Sprintf("%d", pageSize))
	if deviceID != "" {
		params.Set("device_id", deviceID)
	}
	qs := params.Encode()

	// Try channel endpoints with path fallback
	for _, path := range []string{"/api/channels", "/channels"} {
		body, err := c.doGetAuthRetry(ctx, c.baseURL+path+"?"+qs)
		if err != nil {
			continue
		}
		channels, err := c.parseChannelList(body)
		if err == nil && len(channels) > 0 {
			return channels, nil
		}
	}

	// Fallback: extract channels from devices/channels
	devs, err := c.ListDevicesWithChannels(ctx)
	if err != nil {
		return nil, fmt.Errorf("channels endpoint unavailable")
	}
	var channels []Channel
	for _, d := range devs {
		if deviceID != "" && d.ID != deviceID && d.DeviceID != deviceID {
			continue
		}
		for _, ch := range d.Children {
			if ch.DeviceID == "" {
				ch.DeviceID = d.ID
			}
			channels = append(channels, ch)
		}
	}
	return channels, nil
}

