// --- RTSP cache entry ---

const maxCacheSize = 1000 // max cached RTSP URLs

type rtspCacheEntry struct {
	url       string
	expiresAt time.Time
}

// Client is the Hub-side HTTP client for rivision_owl (production-grade).
type Client struct {
	cfg     Config
	baseURL string
	client  *http.Client

	// Auth state
	mu     sync.RWMutex
	token  string
	rsaKey *rsa.PublicKey

	// RTSP URL cache to avoid repeated SIP INVITE
	cacheMu   sync.RWMutex
	rtspCache map[string]*rtspCacheEntry
}

// NewClient creates an OWL API client.
func NewClient(cfg Config) *Client {
	baseURL := cfg.URL
	if baseURL == "" {
		baseURL = "http://localhost:15123"
	}
	baseURL = strings.TrimRight(baseURL, "/")

	if cfg.CacheTTL == 0 {
		cfg.CacheTTL = 5 * time.Minute
	}

	return &Client{
		cfg:       cfg,
		baseURL:   baseURL,
		client:    &http.Client{Timeout: 30 * time.Second},
		rtspCache: make(map[string]*rtspCacheEntry),
	}
}

// IsEnabled reports whether the client is configured and enabled.
func (c *Client) IsEnabled() bool {
	return c.cfg.Enabled && c.baseURL != ""
}

// ─── Authentication ─────────────────────────────────────────────────────────

// Login authenticates with OWL and stores the token.
// Auto-fallback: plain → RSA (or RSA → plain if UseRSAAuth is set).
func (c *Client) Login(ctx context.Context) error {
	if c.cfg.Username == "" {
		return nil // no auth configured, assume open API
	}

	if c.cfg.UseRSAAuth {
		if err := c.loginRSA(ctx); err == nil {
			return nil
		}
		// RSA failed → try plain
		if err := c.loginPlain(ctx); err == nil {
			return nil
		}
		return fmt.Errorf("owl login failed (RSA+plain fallback)")
	}

	// Default: plain first, fallback to RSA
	if err := c.loginPlain(ctx); err == nil {
		return nil
	}
	if err := c.loginRSA(ctx); err == nil {
		return nil
	}
	return fmt.Errorf("owl login failed (plain+RSA fallback)")
}

// EnsureLogin triggers login only if token is empty.
func (c *Client) EnsureLogin(ctx context.Context) error {
	if c.cfg.Username == "" {
		return nil
	}
	c.mu.RLock()
	hasToken := c.token != ""
	c.mu.RUnlock()
	if hasToken {
		return nil
	}
	return c.Login(ctx)
}

func (c *Client) loginPlain(ctx context.Context) error {
	data := map[string]interface{}{
		"username": c.cfg.Username,
		"password": c.cfg.Password,
	}
	body, err := c.doPostRaw(ctx, c.baseURL+"/login", data)
	if err != nil {
		return fmt.Errorf("plain login: %w", err)
	}
	return c.extractToken(body, "plain")
}

func (c *Client) loginRSA(ctx context.Context) error {
	pubKey, err := c.getRSAPublicKey(ctx)
	if err != nil {
		return fmt.Errorf("get RSA key: %w", err)
	}

	credJSON, _ := json.Marshal(map[string]string{
		"username": c.cfg.Username,
		"password": c.cfg.Password,
	})

	ciphertext, err := rsa.EncryptOAEP(sha256.New(), rand.Reader, pubKey, credJSON, nil)
	if err != nil {
		return fmt.Errorf("RSA encrypt: %w", err)
	}

	data := map[string]string{
		"data": base64.StdEncoding.EncodeToString(ciphertext),
	}
	body, err := c.doPostRaw(ctx, c.baseURL+"/login", data)
	if err != nil {
		return fmt.Errorf("RSA login: %w", err)
	}
	return c.extractToken(body, "RSA")
}

func (c *Client) getRSAPublicKey(ctx context.Context) (*rsa.PublicKey, error) {
	c.mu.RLock()
	if c.rsaKey != nil {
		defer c.mu.RUnlock()
		return c.rsaKey, nil
	}
	c.mu.RUnlock()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, c.baseURL+"/login/key", nil)
	if err != nil {
		return nil, err
	}
	resp, err := c.client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("fetch RSA key: %w", err)
	}
	defer resp.Body.Close()

	body, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<16))
	var keyResp struct {
		Key string `json:"key"`
	}
	if err := json.Unmarshal(body, &keyResp); err != nil {
		return nil, fmt.Errorf("parse RSA key response: %w", err)
	}

	pemData, err := base64.StdEncoding.DecodeString(keyResp.Key)
	if err != nil {
		return nil, fmt.Errorf("decode base64 PEM: %w", err)
	}

	block, _ := pem.Decode(pemData)
	if block == nil {
		return nil, fmt.Errorf("PEM decode failed")
	}

	pub, err := x509.ParsePKIXPublicKey(block.Bytes)
	if err != nil {
		return nil, fmt.Errorf("parse public key: %w", err)
	}

	rsaPub, ok := pub.(*rsa.PublicKey)
	if !ok {
		return nil, fmt.Errorf("not an RSA public key")
	}

	c.mu.Lock()
	c.rsaKey = rsaPub
	c.mu.Unlock()
	return rsaPub, nil
}

func (c *Client) extractToken(body []byte, method string) error {
	// Try direct {token: "..."} format
	var direct struct {
		Token string `json:"token"`
	}
	if json.Unmarshal(body, &direct) == nil && direct.Token != "" {
		c.mu.Lock()
		c.token = direct.Token
		c.mu.Unlock()
		return nil
	}

	// Try wrapped {code, data: {token}} format
	var wrapped struct {
		Code int             `json:"code"`
		Data json.RawMessage `json:"data"`
	}
	if json.Unmarshal(body, &wrapped) == nil && len(wrapped.Data) > 0 {
		if json.Unmarshal(wrapped.Data, &direct) == nil && direct.Token != "" {
			c.mu.Lock()
			c.token = direct.Token
			c.mu.Unlock()
			return nil
		}
	}

	return fmt.Errorf("%s login: no token in response", method)
}

// clearToken forces re-authentication on next request.
func (c *Client) clearToken() {
	c.mu.Lock()
	c.token = ""
	c.mu.Unlock()
}

// ─── Server Info ─────────────────────────────────────────────────────────────

// GetServerInfo returns OWL server info (with fallback paths).
func (c *Client) GetServerInfo(ctx context.Context) (*ServerInfo, error) {
	if err := c.EnsureLogin(ctx); err != nil {
		return nil, err
	}

	var info ServerInfo
	for _, path := range []string{"/api/server/info", "/health"} {
		body, err := c.doGetAuth(ctx, c.baseURL+path)
		if err != nil {
			continue
		}
		parsed, err := c.parseResponse(body)
		if err != nil {
			continue
		}
		if json.Unmarshal(parsed, &info) == nil && info.Version != "" {
			return &info, nil
		}
	}
	return nil, fmt.Errorf("server info endpoint unavailable")
}

// ProbeCapabilities checks which OWL API endpoints are available.
func (c *Client) ProbeCapabilities(ctx context.Context) *Capabilities {
	caps := &Capabilities{}

	if err := c.Login(ctx); err == nil {
		caps.Login = true
	}
	if _, err := c.GetServerInfo(ctx); err == nil {
		caps.ServerInfo = true
	}
	if _, err := c.ListChannels(ctx); err == nil {
		caps.Channels = true
	}
	if _, err := c.ListDevices(ctx); err == nil {
		caps.Devices = true
	}
	if _, err := c.ListDevicesWithChannels(ctx); err == nil {
		caps.DevicesWithChannels = true
	}
	caps.Play = caps.Channels || caps.DevicesWithChannels
	caps.Snapshot = caps.Play
	caps.PTZ = caps.Play

	return caps
}

