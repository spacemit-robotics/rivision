// Config holds OWL integration configuration for Hub.
type Config struct {
	URL          string        `yaml:"url" json:"url"`                     // OWL HTTP API base URL (default http://localhost:15123)
	Username     string        `yaml:"username" json:"username"`           // OWL login username
	Password     string        `yaml:"password" json:"password"`           // OWL login password
	UseRSAAuth   bool          `yaml:"use_rsa_auth" json:"use_rsa_auth"`  // use RSA OAEP login (GoWVP mode)
	PollInterval time.Duration `yaml:"poll_interval" json:"poll_interval"` // device status poll interval (default 60s)
	Enabled      bool          `yaml:"enabled" json:"enabled"`
	CacheTTL     time.Duration `yaml:"cache_ttl" json:"cache_ttl"`        // RTSP URL cache TTL (default 5min)
}

// DefaultConfig returns production defaults.
func DefaultConfig() Config {
	return Config{
		URL:          "http://localhost:15123",
		PollInterval: 60 * time.Second,
		CacheTTL:     5 * time.Minute,
		Enabled:      true,
	}
}

